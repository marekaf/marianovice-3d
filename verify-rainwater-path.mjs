import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import * as THREE from 'three';
import {createMeshHeightQuery} from './mesh-height-query.js';
const require=createRequire(import.meta.url);
const {GARDEN}=require('./layout.js'),{GardenRouteModel}=require('./garden-route-model.js');
const tank=GARDEN.elements.find(e=>e.id==='rainTank'),lid=tank.meta.accessCover;
assert.deepEqual(lid,{x:37.13,z:17.8});
const footprint=tank.parts.find(p=>p.kind==='rect');
assert.deepEqual([footprint.x,footprint.y,footprint.w,footprint.d],[36.13,17.2,2,2.5]);
assert(GardenRouteModel.distance(GARDEN.gardenRoutes,lid.x,lid.z)>.60,'The rainwater lid and a clear margin must lie outside every path');
const data=GardenRouteModel.geometry(GARDEN.gardenRoutes,()=>0),geometry=new THREE.BufferGeometry();
geometry.setAttribute('position',new THREE.Float32BufferAttribute(data.positions,3));
const height=createMeshHeightQuery(geometry);
for(let r=0;r<=.6;r+=.05)for(let i=0;i<72;i++)assert.equal(height(lid.x+Math.cos(i*Math.PI/36)*r,lid.z+Math.sin(i*Math.PI/36)*r),null);
const pond=GARDEN.gardenRoutes.find(r=>r.id==='Pond walk'),service=GARDEN.gardenRoutes.find(r=>r.id==='Service connection');
assert.deepEqual(pond.points[pond.approachStart],service.points[0],'The service route joins the pond route at its grading junction');
for(let i=0;i<72;i++)assert.notEqual(height(service.points[0][0]+Math.cos(i*Math.PI/36)*.5,service.points[0][1]+Math.sin(i*Math.PI/36)*.5),null);
console.log('Rainwater lid: fixed utility positions, 936 clear-margin mesh probes and full-width route junction pass');
