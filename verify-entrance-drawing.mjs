import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {entranceDrawing} from './docs/entrance-drawing.js';
const {HOUSE_INTERIOR:house}=createRequire(import.meta.url)('./house-interior.js');
const before=JSON.stringify(house),drawing=entranceDrawing(house);
const dimension=id=>drawing.dimensions.find(d=>d.id===id);
assert.equal(dimension('overall-width').label,'3568');
assert.equal(dimension('overall-depth').label,'600');
assert.equal(dimension('overall-height').label,'2504');
assert.equal(dimension('entrance_sloped_front_0-width').label,'466');
assert.equal(dimension('entrance_sloped_front_1-width').label,'636');
assert.equal(dimension('Sedák · šířka').label,'723');
assert.equal(dimension('Sedák · hloubka').label,'570');
assert.equal(dimension('Zrcadlo · výška').label,'1500');
assert.equal(dimension('coat-width').label,'820');
assert(drawing.svg.includes('Čelní pohled')&&drawing.svg.includes('Půdorys'));
assert(!/NaN|undefined|Infinity/.test(drawing.svg));
assert.equal(JSON.stringify(house),before,'Drawing never changes the shared joinery');
const taller=entranceDrawing({...house,stairs:{...house.stairs,rise:house.stairs.rise+.01}});
assert(taller.dimensions.find(d=>d.id==='overall-height').value>dimension('overall-height').value+.12,'Drawing follows changed source geometry');
console.log('Entrance drawing: actual front/module/depth/seat/mirror dimensions and unchanged model pass');
