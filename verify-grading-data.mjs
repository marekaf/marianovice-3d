import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFileSync } from 'node:fs';
import { runInNewContext } from 'node:vm';
const require = createRequire(import.meta.url);
const { createGradingData } = require('./grading-data.js');
const { SurveySurface } = require('./survey-surface.js');
const terrain = { houseFFLInternal: 2 };
const garden = { plot: { vertices: [[0, 0], [2, 0], [2, 2], [0, 2]] }, elements: [], gardenRoutes: [{ id: 'Daily dining', points: [[0, 1], [2, 1]] }] };
const survey = SurveySurface.create([[0, 0, 1], [2, 0, 1], [2, 2, 1], [0, 2, 1]], { a: 0, b: 0, c: 1 });
const build = (height, extra = {}) => createGradingData({ garden, terrain, survey, site: { height, spec: {} }, ...extra });
const fill = build(() => 2);
assert.equal(fill.totals.fill, 4);
assert.equal(fill.totals.cut, 0);
assert.equal(fill.totals.area, 4);
assert.equal(fill.cells.length, 16);
const cut = build(() => .5);
assert.equal(cut.totals.cut, 2);
const slope = build(x => 1 + x / 10);
for (const cell of slope.cells) assert.ok(Math.abs(cell.slope - 10) < 1e-10);
assert.ok(Math.abs(slope.sections[0].maxSlope - 10) < 1e-10);
assert.ok(Math.abs(slope.totals.fill - .4) < 1e-10);
const excluded = build(() => 2, { garden: { ...garden, elements: [{ id: 'house', parts: [{ kind: 'rect', x: 0, y: 0, w: 1, d: 2 }] }] } });
assert.equal(excluded.totals.fill, 2);
assert.equal(excluded.totals.excludedArea, 2);
const polygonExcluded = build(() => 2, { garden: { ...garden, elements: [{ id: 'house', parts: [{ kind: 'polygon', points: [[0, 0], [1, 0], [1, 2], [0, 2]] }] }] } });
assert.deepEqual(polygonExcluded.totals, excluded.totals);
const halfSurvey = SurveySurface.create([[0, 0, 1], [1, 0, 1], [1, 2, 1], [0, 2, 1]], { a: 0, b: 0, c: 1 });
const partial = build(() => 2, { survey: halfSurvey });
assert.equal(partial.totals.area, 2);
assert.equal(partial.totals.fill, 2);
assert.equal(partial.totals.extrapolatedArea, 2);
assert.equal(partial.totals.extrapolatedFill, 2);
const outsideSurvey = SurveySurface.create([[5, 5, 1], [7, 5, 1], [5, 7, 1]], { a: 0, b: 0, c: 1 });
const extrapolated = build(() => 2, { survey: outsideSurvey });
assert.equal(extrapolated.totals.area, 0);
assert.equal(extrapolated.totals.fill, 0);
assert.equal(extrapolated.totals.extrapolatedArea, 4);
assert.equal(extrapolated.totals.extrapolatedFill, 4);
assert.throws(() => build(() => NaN), /Non-finite/);
assert.throws(() => build(() => 1, { survey: undefined }), /triangulated survey/);
const empty = build(() => 2, { garden: { ...garden, plot: { vertices: [[0, 0], [.1, 0], [0, .1]] } } });
assert.equal(empty.cells.length, 0);
assert.equal(empty.totals.fill, 0);
for (const section of fill.sections) for (const sample of section.samples) assert.ok([sample.distance, sample.existing, sample.proposed].every(Number.isFinite));
const browserModule = runInNewContext(`${readFileSync(new URL('./grading-data.js', import.meta.url), 'utf8')}\nGradingData`);
const browserData = browserModule.createGradingData({ garden, terrain, survey, site: { height: () => 2, spec: {} } });
assert.deepEqual(JSON.parse(JSON.stringify(browserData)), fill);
console.log('Grading data: analytic cut/fill, slope, footprint exclusions, survey coverage and finite sections pass');
