import assert from 'node:assert/strict';
import * as THREE from 'three';
import {createWalkDoors} from './walk-doors.js';
const wall={id:'partition',a:[0,0],b:[4,.2],h:2.52,openings:[{at:1,w:1,h:2}]};
const data={originPlot:{x:0,z:0},clearH:2.52,extWalls:[],intWalls:[wall],buildOpening:()=>null};
const ground=createWalkDoors(THREE,{data,doors:[],floorY:0});
assert(!ground.canStandAt(.5,.1,3.6),'An elevated walker still intersects a 2.52 m wall');
assert(ground.canStandAt(.5,.1,4.62),'A walker on the loft floor clears the ground wall');
assert(ground.canStandAt(1.5,.1,1.7),'Ground doorway is open at normal eye height');
assert(!ground.canStandAt(1.5,.1,2.2),'Elevated eye height intersects the doorway header');
const loft=createWalkDoors(THREE,{data,doors:[],floorY:2.92});
assert(loft.canStandAt(.5,.1,1.7),'Loft partitions do not block ground-floor movement');
assert(!loft.canStandAt(.5,.1,4.62),'Loft partitions block at loft eye height');
const low=createWalkDoors(THREE,{data:{...data,intWalls:[{...wall,h:.2,openings:[]}]},doors:[],floorY:2.92});
assert(!low.canStandAt(.5,.1,4.62),'A low upstand still intersects the walker feet');
const slope=createWalkDoors(THREE,{data:{...data,intWalls:[{...wall,profile:[[0,.2],[4,2.52]],openings:[]}]},doors:[],floorY:0});
assert(slope.canStandAt(.5,.1,3),'Walker clears the low end of a sloped wall');
assert(!slope.canStandAt(3.5,.1,3),'Walker intersects the high end of a sloped wall');
const tall=createWalkDoors(THREE,{data:{...data,intWalls:[{...wall,profile:[[0,4],[4,4]],openings:[]}],wallRecesses:()=>[],subtractWallRecesses:cell=>[cell]},doors:[],floorY:0});
assert(!tall.canStandAt(.5,.1,4.62),'Recess cells retain the full height of a profiled wall');
console.log('Walk collision respects floor offsets, wall heights, profiles and doorway headers');
