import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import * as THREE from 'three';
import {buildModel} from './model3d.js';
import {buildWalkingDoor,createWalkDoors} from './walk-doors.js';
const {HOUSE_INTERIOR:data}=createRequire(import.meta.url)('./house-interior.js');
const office=data.intWalls.find(w=>w.id==='W22');
const model=data.buildOpening(office,office.openings[0],0);
assert(model.doorMotion,'Door models must expose a rigid leaf pivot without moving the frame');
assert(model.doorMotion.movingParts.includes('opening_W22_0_leaf'));
assert(model.doorMotion.movingParts.includes('opening_W22_0_lever_1'));
assert(!model.doorMotion.movingParts.includes('opening_W22_0_head'));
assert.equal(model.opening.hinge,'north');
assert.equal(model.doorMotion.angle,-Math.PI/2);
const entrance=data.extWalls.find(w=>w.id==='W9');
const front=data.buildOpening(entrance,entrance.openings[2],2);
assert.equal(front.opening.hinge,'south');
assert.equal(front.doorMotion.angle,Math.PI/2);
assert(!front.doorMotion.movingParts.some(name=>name.includes('sidelight')));
globalThis.document={createElement(){return{getContext(){return{createImageData(w,h){return{data:new Uint8ClampedArray(w*h*4)};},putImageData(){}};}};}};
const group=buildWalkingDoor(THREE,model,buildModel);
group.position.set(data.originPlot.x,2.465,data.originPlot.z);
const controller=createWalkDoors(THREE,{data,doors:[group],floorY:2.465});
const spawn=new THREE.Vector3(20,4.165,20);
assert(controller.recover(spawn),'An occupied initial spawn relocates to clear nearby ground');
assert(controller.canStandAt(spawn.x,spawn.z));
assert(spawn.distanceTo(new THREE.Vector3(20,4.165,20))<1);
const fixed=group.userData.categories.openings;
group.updateMatrixWorld(true);
const fixedBounds=new THREE.Box3().setFromObject(fixed),leafBounds=new THREE.Box3().setFromObject(group.userData.walkDoor.leaf);
const camera=new THREE.PerspectiveCamera();
camera.position.set(leafBounds.min.x+1.4,4.165,(leafBounds.min.z+leafBounds.max.z)/2);
camera.lookAt(leafBounds.getCenter(new THREE.Vector3()).setY(4.165));camera.updateMatrixWorld(true);
assert.equal(controller.aimedDoor(camera),group,'Near aimed door is available');
assert(!controller.canStandAt(leafBounds.getCenter(new THREE.Vector3()).x,leafBounds.getCenter(new THREE.Vector3()).z));
assert(controller.toggle(group,camera),'Door opens from outside its swing');
assert.deepEqual(new THREE.Box3().setFromObject(fixed),fixedBounds,'Frames stay fixed');
assert.equal(group.userData.walkDoor.open,true);
const center=leafBounds.getCenter(new THREE.Vector3());
assert(controller.canStandAt(center.x,center.z),'Open doorway permits passage');
assert(!controller.canStandAt(data.originPlot.x+4.6,data.originPlot.z+14.8),'Adjacent solid wall blocks passage');
const position=new THREE.Vector3(center.x+1,4.165,center.z);
controller.constrain(position,center.x-1,center.z);
assert(Math.abs(position.x-center.x-1)<1e-7,'Walker can pass open doorway');
assert(controller.toggle(group,camera),'Door closes with walker outside swing');
position.set(center.x+1,4.165,center.z);
controller.constrain(position,center.x-1,center.z);
assert(position.x<center.x,'Substeps prevent tunnelling through closed leaf');
assert(controller.toggle(group,camera));
camera.position.set(center.x,4.165,center.z);
assert(!controller.toggle(group,camera),'Door cannot close through the walker');
assert.equal(group.userData.walkDoor.open,true);
const allDoors=[...data.extWalls,...data.intWalls].flatMap(wall=>wall.openings.flatMap((opening,index)=>{
  const model=data.buildOpening(wall,opening,index);
  if(!model?.doorMotion)return[];
  const group=buildWalkingDoor(THREE,model,buildModel);
  group.position.set(data.originPlot.x,2.465,data.originPlot.z);return[group];
}));
assert.equal(allDoors.length,11);
const allController=createWalkDoors(THREE,{data,doors:allDoors,floorY:2.465});
for(const door of allDoors){
  const {panel,opening}=door.userData.walkDoor;
  const center=door.localToWorld(new THREE.Vector3(panel.position[0],1.7,panel.position[1]));
  assert(!allController.canStandAt(center.x,center.z),`${door.name}: closed leaf blocks`);
  camera.position.copy(center);
  if(opening.axis==='z')camera.position.x+=1.4;else camera.position.z+=1.4;
  assert(allController.toggle(door,camera),`${door.name}: opens from a clear standing position`);
  assert(allController.canStandAt(center.x,center.z),`${door.name}: open leaf clears its doorway`);
  for(const sign of [-1,1]){
    const alongX=opening.axis==='z',delta=sign*.4;
    const position=center.clone();if(alongX)position.x+=delta;else position.z+=delta;
    const previousX=center.x-(alongX?delta:0),previousZ=center.z-(alongX?0:delta);
    allController.constrain(position,previousX,previousZ);
    assert(Math.abs((alongX?position.x:position.z)-(alongX?center.x:center.z)-delta)<1e-6,`${door.name}: passage in direction ${sign}`);
  }
}
console.log('Walking doors: rigid leaf and hardware, fixed frames and recorded hinges pass');
